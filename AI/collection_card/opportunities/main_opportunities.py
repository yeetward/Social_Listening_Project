def log(msg: str, verbose: bool):
    if verbose:
        print(msg, file=sys.stderr)


def _build_industry_text_filter(industry_name: str) -> Dict[str, Any]:
    """
    Case-insensitive filter that matches ai_title, ai_summary, tags (array), and source.
    Escapes special regex chars and allows flexible whitespace.
    """
    if not industry_name:
        return {}

    escaped = re.escape(industry_name.strip())
    flexible = re.sub(r"\\\s+", r"\\s+", escaped)
    rx = {"$regex": flexible, "$options": "i"}

    return {
        "$or": [
            {"ai_title": rx},
            {"ai_summary": rx},
            {"source": rx},
            {"tags": {"$elemMatch": rx}},
        ]
    }


def get_company_context(company_name: str) -> dict:
    """
    Fetch company description + competitors for context (company_profiles schema).
    {
      name: "Robotic Marketer",
      description: "...",
      competitors: ["Company A", "Company B", ...]
    }
    """
    company = db.company_profiles.find_one({"name": company_name})
    if not company:
        raise ValueError(f"No company_profile found for '{company_name}'")

    return {
        "company": company["name"],
        "description": company.get("description", ""),
        "competitors": company.get("competitors", []),
    }


def _fetch_recent_generic_articles(
    limit: int = 20, min_relevance: float = 0.25
) -> List[Dict[str, Any]]:
    """
    Fallback: if industry-matching articles are too few, pull recent relevant ones globally.
    """
    cur = (
        db.ai_results.find(
            {"status": "done", "relevance_score": {"$gte": float(min_relevance)}},
            {
                "_id": 0,
                "ai_title": 1,
                "ai_summary": 1,
                "uri": 1,
                "source": 1,
                "relevance_score": 1,
                "published_ts": 1,
                "tags": 1,
            },
        )
        .sort([("published_ts", -1), ("relevance_score", -1)])
        .limit(int(limit))
    )
    return list(cur)


def _ensure_min_articles(
    articles: List[Dict[str, Any]], industry_name: str, desired_min: int, verbose: bool
) -> List[Dict[str, Any]]:
    """
    Ensure we have enough articles to feed the LLM.
    Strategy:
      1) If count >= desired_min → return as-is
      2) Else: relax relevance threshold and fetch more industry matches (best-effort)
      3) Else: top-up with recent generic articles
    """
    if len(articles) >= desired_min:
        return articles

    # Try to relax relevance a bit for this industry
    try:
        extra_needed = desired_min - len(articles)
        relaxed = get_industry_articles(
            industry_name=industry_name, limit=extra_needed * 2, min_relevance=0.2
        )
        # Merge (dedupe by uri/title)
        seen = set()
        merged: List[Dict[str, Any]] = []
        for a in articles + relaxed:
            key = a.get("uri") or a.get("ai_title", "")
            if key and key not in seen:
                seen.add(key)
                merged.append(a)
        if len(merged) >= desired_min:
            log(f" Relaxed filter supplied {len(merged)} total articles", verbose)
            return merged[: max(len(articles), desired_min)]
        articles = merged
    except Exception as _:
        pass

    # Still short? Top-up with recent generic articles
    if len(articles) < desired_min:
        top_up = _fetch_recent_generic_articles(
            limit=(desired_min - len(articles) + 5), min_relevance=0.25
        )
        log(f"🧩 Topping up with {len(top_up)} generic articles", verbose)
        seen = set((a.get("uri") or a.get("ai_title", "")) for a in articles)
        for a in top_up:
            key = a.get("uri") or a.get("ai_title", "")
            if key and key not in seen:
                articles.append(a)
                seen.add(key)

    # Cap to a sane number (LLM context)
    return articles[: max(desired_min, min(len(articles), 30))]


def _priority_weight(val: str) -> float:
    table = {"critical": 1.0, "high": 0.85, "medium": 0.6, "low": 0.35}
    return table.get(str(val).lower(), 0.5)


def _impact_weight(val: str) -> float:
    table = {"high": 0.9, "medium": 0.6, "low": 0.3}
    return table.get(str(val).lower(), 0.5)


def _urgency_weight(val: str) -> float:
    table = {"immediate": 1.0, "this week": 0.85, "this month": 0.6, "low": 0.35}
    return table.get(str(val).lower(), 0.5)


def _dedupe_opportunities(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Deduplicate by (action/headline/opportunity) + source_article if present.
    """
    seen = set()
    out: List[Dict[str, Any]] = []
    for it in items:
        key = (
            (it.get("action") or it.get("headline") or it.get("opportunity") or "")
            .strip()
            .lower(),
            (it.get("source_article") or "").strip().lower(),
        )
        if key not in seen:
            seen.add(key)
            out.append(it)
    return out


def _re_rank_opportunities(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Add a composite score and sort:
      score = 0.45*priority + 0.35*impact + 0.20*urgency
    Then cap to a clean list.
    """
    scored = []
    for it in items:
        pri = _priority_weight(it.get("priority", it.get("urgency", "medium")))
        imp = _impact_weight(
            it.get("estimated_impact", it.get("potential_impact", "medium"))
        )
        urg = _urgency_weight(it.get("urgency", "this month"))
        score = 0.45 * pri + 0.35 * imp + 0.20 * urg
        it["_score"] = round(float(score), 4)
        scored.append(it)
    scored.sort(key=lambda x: x.get("_score", 0.0), reverse=True)
    return scored


def _fallback_from_articles(
    company_ctx: dict, industry_name: str, articles: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    If the LLM call fails or returns empty, produce simple, deterministic opportunities from article titles.
    """
    out = []
    for a in articles[:6]:
        title = a.get("ai_title") or a.get("source") or "Industry update"
        url = a.get("uri", "")
        out.append(
            {
                "category": "opportunity",
                "action": f"Explore partnership or content collab based on: {title}",
                "priority": "high",
                "description": f"Leverage {title} to position {company_ctx['company']} in {industry_name}. Consider a quick outreach or a response article.",
                "source_article": title,
                "source_url": url,
                "estimated_effort": "low",
                "estimated_impact": "medium",
                "urgency": "This week",
            }
        )
    return out



def run(
    company_name: str,
    industry_name: str,
    limit: int = 20,
    min_relevance: float = 0.4,
    verbose: bool = False,
) -> List[Dict[str, Any]]:
    """
    Programmatic entry point for generating growth/partnership/expansion opportunities.
    Robust to sparse industry matches and LLM hiccups.
    """
    try:
        log(f"Loading company context for {company_name}...", verbose)
        company_ctx = get_company_context(company_name)

        log(f" Fetching {limit} recent '{industry_name}' articles...", verbose)
        articles = get_industry_articles(
            industry_name=industry_name,
            limit=limit,
            min_relevance=min_relevance,
        )
        log(f" Found {len(articles)} industry-matching articles", verbose)

        # Ensure we have enough signal to feed the LLM well
        articles = _ensure_min_articles(
            articles, industry_name, desired_min=8, verbose=verbose
        )
        log(f" Using {len(articles)} articles after top-up", verbose)

        # Generate via LLM
        log(" Generating opportunities...", verbose)
        opps = generate_opportunities(
            company_context=company_ctx,
            industry_name=industry_name,
            industry_articles=articles,
        )

        # Guard against non-list returns
        if not isinstance(opps, list):
            raise ValueError("generate_opportunities returned non-list")

        # Deduplicate and re-rank
        opps = _dedupe_opportunities(opps)
        opps = _re_rank_opportunities(opps)

        # Attach industry context for traceability
        for it in opps:
            it.setdefault("industry", industry_name)

        log(f" Generated {len(opps)} opportunities", verbose)

        # Graceful fallback if empty
        if not opps:
            log(
                " LLM returned empty; building deterministic fallbacks from articles",
                verbose,
            )
            opps = _fallback_from_articles(company_ctx, industry_name, articles)
            opps = _re_rank_opportunities(opps)

        return opps

    except Exception as e:
        # Last-resort graceful degradation: return deterministic fallbacks
        try:
            log(
                f"opportunities.run() error: {e}. Falling back to deterministic suggestions.",
                verbose,
            )
            # try to fetch generic articles to seed fallbacks
            articles = _fetch_recent_generic_articles(limit=10, min_relevance=0.25)
            company_ctx = get_company_context(company_name)
            opps = _fallback_from_articles(company_ctx, industry_name, articles)
            return _re_rank_opportunities(opps)
        except Exception as _:
            # If even fallback fails, surface the original error
            raise RuntimeError(f"opportunities.run() failed: {e}") from e


